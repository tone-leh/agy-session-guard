  function getSagStrings(lang) {
    const norm = normalizeLang(lang);
    if (norm === 'zh-CN' || norm === 'yue') return SAG_UI_PACKS['zh-CN'];
    if (norm === 'zh-TW') return SAG_UI_PACKS['zh-TW'];
    return SAG_UI_PACKS.en;
  }

  function normalizeLang(raw) {
    const s = String(raw || '').trim().toLowerCase().replace(/_/g, '-');
    if (/^yue\b|^zh-(?:hk|mo)/.test(s)) return 'yue';
    if (/^zh-(?:tw|hant)/.test(s)) return 'zh-TW';
    if (/^zh/.test(s)) return 'zh-CN';
    if (/^(?:ja|jp)/.test(s)) return 'ja';
    if (/^(?:ko|kr)/.test(s)) return 'ko';
    if (/^es/.test(s)) return 'es';
    if (/^fr/.test(s)) return 'fr';
    if (/^de/.test(s)) return 'de';
    if (/^en/.test(s)) return 'en';
    if (/^(?:ru|pt)/.test(s)) return 'en';
    return 'zh-CN';
  }

  function detectLang(doc, win) {
    const html = doc?.documentElement;
    const raw =
      html?.getAttribute?.('data-ag-sag-lang') ||
      html?.getAttribute?.('data-ag-cs-lang') ||
      html?.getAttribute?.('lang') ||
      win?.navigator?.language ||
      'zh-CN';
    return normalizeLang(raw);
  }

  function getStrings(lang) {
    return PACKS[normalizeLang(lang)] || PACKS['zh-CN'];
  }

  function formatTemplate(tpl, vars) {
    return String(tpl || '').replace(/\{([a-zA-Z0-9_]+)\}/g, (_, k) =>
      vars && Object.prototype.hasOwnProperty.call(vars, k) ? String(vars[k]) : ''
    );
  }

  return { PACKS, SAG_UI_PACKS, normalizeLang, detectLang, getStrings, getSagStrings, formatTemplate };
